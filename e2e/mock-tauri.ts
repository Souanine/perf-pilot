/**
 * Tauri IPC shim for the e2e suite.
 *
 * `@tauri-apps/api/core::invoke` resolves `window.__TAURI_INTERNALS__.invoke`;
 * `@tauri-apps/api/event::listen` does the same with `transformCallback`.
 * We inject both before the page's JS runs so the real frontend stores
 * (`useAppStore`, `useRunsStore`, etc.) can call into a stub that
 * returns deterministic test data.
 *
 * State is held on `window.__MOCK_TAURI__`; tests can read or mutate it
 * via `page.evaluate`. Recorded invoke calls land in `__INVOKE_LOG__`
 * for assertions like "clicking Start should call `run_k6` with the
 * right script path".
 */

import type { Page } from "@playwright/test";

export interface MockAppInfo {
  app_version: string;
  k6_info: { version: string; path: string } | null;
  app_data_dir: string;
  scripts_dir: string;
  runs_dir: string;
}

export interface MockScriptFile {
  path: string;
  name: string;
  size: number;
  modified_at: string;
}

export interface MockRunRecord {
  run_id: string;
  label: string | null;
  status: string;
  started_at: string;
  finished_at: string | null;
  exit_code: number | null;
  script_path: string;
  p95_ms?: number | null;
  rps?: number | null;
  error_rate_pct?: number | null;
}

export interface InvokeCall {
  cmd: string;
  args: unknown;
  /** wall-clock order index, useful for assertions like "the third
   *  call to `generate_script_stream` had these args". */
  index: number;
}

export interface MockSpec {
  appInfo?: Partial<MockAppInfo>;
  scripts?: MockScriptFile[];
  runs?: MockRunRecord[];
  /** Body the streaming `generate_script_stream` mock will deliver as
   *  delta chunks. Defaults to a small k6 script. */
  streamScript?: string;
  /** Override per-chunk byte length. Defaults to 24. */
  streamChunkSize?: number;
  /** Override the gap between chunks (ms). Defaults to 30. */
  streamChunkDelayMs?: number;
  /** LLM provider catalog. Defaults to one OpenAI-shaped provider so
   *  the Settings page has something to render. */
  llmProviders?: Array<{
    id: string;
    name: string;
    api_format: string;
    base_url: string;
    api_key: string;
    model: string;
    organization: string | null;
    temperature: number;
    models: Array<{ id: string; label?: string | null }>;
  }>;
}

const DEFAULT_SCRIPT = [
  "// generated by e2e mock",
  'import http from "k6/http";',
  'import { check, sleep } from "k6";',
  "",
  "export const options = { vus: 5, duration: \"10s\" };",
  "",
  "export default function () {",
  "  const res = http.get(\"https://test.k6.io/\");",
  "  check(res, { \"status is 200\": r => r.status === 200 });",
  "  sleep(1);",
  "}",
  "",
].join("\n");

const DEFAULT_PROVIDERS = [
  {
    id: "default-openai",
    name: "OpenAI",
    api_format: "chat_completions",
    base_url: "https://api.openai.com/v1",
    api_key: "",
    model: "gpt-4o-mini",
    organization: null,
    temperature: 0.2,
    models: [{ id: "gpt-4o-mini", label: "GPT-4o mini" }],
  },
];

/**
 * Inject the Tauri shim into the page before any user script runs.
 *
 * The shim is installed in stages so each `addInitScript` payload
 * stays small (which is more reliable than passing a multi-kilobyte
 * string through Playwright's transport). Order matters: spec first,
 * then state, then dispatcher, then internals, then event handlers.
 */
export async function installTauriMocks(page: Page, spec: MockSpec = {}) {
  const merged = {
    appInfo: {
      app_version: "0.1.0-test",
      k6_info: { version: "v0.50.0", path: "/usr/local/bin/k6" },
      app_data_dir: "/tmp/perf-pilot-test",
      scripts_dir: "/tmp/perf-pilot-test/scripts",
      runs_dir: "/tmp/perf-pilot-test/runs",
      ...spec.appInfo,
    },
    scripts: spec.scripts ?? [],
    runs: spec.runs ?? [],
    streamScript: spec.streamScript ?? DEFAULT_SCRIPT,
    streamChunkSize: spec.streamChunkSize ?? 24,
    streamChunkDelayMs: spec.streamChunkDelayMs ?? 30,
    llmProviders: spec.llmProviders ?? DEFAULT_PROVIDERS,
  };

  // 1. Spec-setter — small payload, runs first, puts the merged
  //    spec on `window` so the dispatcher can read it.
  await page.addInitScript((s: string) => {
    (window as any).__MOCK_TAURI_SPEC__ = s;
  }, JSON.stringify(merged));

  // 2. State — derives from the spec and stashes everything the
  //    dispatcher will read.
  await page.addInitScript(function () {
    const raw = (window as any).__MOCK_TAURI_SPEC__;
    if (!raw) return;
    const spec = JSON.parse(raw);
    (window as any).__MOCK_TAURI__ = {
      appInfo: spec.appInfo,
      scripts: spec.scripts,
      runs: spec.runs,
      streamScript: spec.streamScript,
      streamChunkSize: spec.streamChunkSize,
      streamChunkDelayMs: spec.streamChunkDelayMs,
      llmProviders: spec.llmProviders,
      nextRunId: "r-test-1",
    };
    (window as any).__INVOKE_LOG__ = [];
  });

  // 3. Dispatcher — defines `dispatch(cmd, args)` and stashes it on
  //    window. Reads/writes state via `window.__MOCK_TAURI__`.
  await page.addInitScript(function () {
    const state = (window as any).__MOCK_TAURI__;
    const log = (window as any).__INVOKE_LOG__;
    if (!state || !log) return;
    function record(cmd: string, args: unknown) {
      log.push({ cmd, args, index: log.length });
    }
    // Plugin-store protocol: each load returns a fresh rid;
    // get/set/has/delete/save/etc. key into a Map by rid.
    let nextRid = 1;
    const stores = new Map();
    // Stand-in for the OS credential store (keychain / Credential
    // Manager / Secret Service). Deliberately separate from `stores` so a
    // spec asserting on the settings JSON can't see keys that the real
    // backend keeps out of it.
    const secrets = new Map<string, string>();
    // plugin-event protocol: listen/emit route through invoke.
    const eventHandlers = new Map(); // event -> Map<handlerId, callback>
    let nextHandlerId = 1;
    function fire(event: string, payload: unknown) {
      // Mirror llm://chunk frames into a window-level log so e2e
      // tests can assert on the streaming pipeline.
      if (event === "llm://chunk" && payload && typeof payload === "object") {
        if (!(window as any).__STREAM_FRAMES__) (window as any).__STREAM_FRAMES__ = [];
        (window as any).__STREAM_FRAMES__.push(payload);
      }
      const handlers = eventHandlers.get(event);
      if (!handlers) return;
      handlers.forEach((cb: any) => {
        try { cb({ event, id: 0, payload }); } catch {}
      });
    }
    function streamBody(
      requestId: string,
      body: string,
      chunkSize: number,
      delayMs: number,
      donePayload: Record<string, unknown>,
    ) {
      let i = 0;
      function emitOne() {
        if (i >= body.length) {
          fire("llm://chunk", Object.assign({}, donePayload, { request_id: requestId }));
          return;
        }
        const text = body.slice(i, i + chunkSize);
        fire("llm://chunk", { phase: "delta", request_id: requestId, text });
        i += chunkSize;
        setTimeout(emitOne, delayMs);
      }
      fire("llm://chunk", { phase: "started", request_id: requestId, model: "mock" });
      setTimeout(emitOne, delayMs);
    }
    function dispatch(cmd: string, args: any) {
      record(cmd, args);
      switch (cmd) {
        case "ensure_dirs":
        case "delete_run":
        case "delete_script":
        case "write_script":
        case "delete_report":
          return null;
        case "get_app_info":
          return state.appInfo;
        case "list_scripts":
          return state.scripts;
        case "list_runs":
          return state.runs;
        case "list_reports":
        case "list_reports":
          return [];
        case "run_k6":
          state.nextRunId = "r-" + Math.random().toString(36).slice(2, 10);
          return state.nextRunId;
        case "stop_k6":
          return true;
        case "get_run_output": {
          // Build a canned RunOutput from the matching seeded run
          // record (if any). When `runs` doesn't include the id the
          // History page treats it as "deleted", which is the same
          // behaviour as a missing file.
          const match = (state.runs || []).find(
            (r: { run_id: string }) => r.run_id === args?.runId,
          );
          if (!match) return null;
          return {
            run_id: match.run_id,
            script_path: match.script_path,
            label: match.label,
            started_at: match.started_at,
            finished_at: match.finished_at,
            exit_code: match.exit_code,
            status: match.status,
            stdout: `// mocked stdout for ${match.run_id}\n`,
            stderr: "",
            metrics: [],
            error: null,
          };
        }
        case "read_script":
          return null;
        case "test_llm":
          return { ok: true, message: "mock connected", model: "mock" };
        case "generate_script":
          return {
            script: "// mocked k6 script\n",
            explanation: "Mock explanation.",
            model: "mock",
            tokens_in: 42,
            tokens_out: 100,
          };
        case "generate_script_stream": {
          const requestId = (args && args.requestId) || ("s-" + Math.random().toString(36).slice(2));
          streamBody(requestId, state.streamScript, state.streamChunkSize, state.streamChunkDelayMs, {
            phase: "done",
            text: state.streamScript,
            model: "mock",
            tokens_in: 10,
            tokens_out: state.streamScript.length,
          });
          return {
            script: state.streamScript,
            explanation: null,
            model: "mock",
            tokens_in: 10,
            tokens_out: state.streamScript.length,
          };
        }
        case "generate_report_stream": {
          const requestId = (args && args.requestId) || ("s-" + Math.random().toString(36).slice(2));
          const body = "# Mock report\n\nAll systems nominal.";
          streamBody(requestId, body, state.streamChunkSize, state.streamChunkDelayMs, {
            phase: "done",
            text: body,
            model: "mock",
            tokens_in: 10,
            tokens_out: body.length,
          });
          return { report: body, model: "mock", tokens_in: 10, tokens_out: body.length };
        }
        case "generate_report":
          return { report: "# Mock report\n\nAll good.", model: "mock", tokens_in: 10, tokens_out: 20 };
        case "read_report":
          return "# mock";
        // Secret store — in-memory stand-in for the OS credential store.
        // Keys must never round-trip through the plugin-store JSON, so
        // these live in their own map, mirroring secrets.rs.
        case "secret_get":
          return secrets.get(args.providerId) ?? null;
        case "secret_set":
          secrets.set(args.providerId, args.value);
          return null;
        case "secret_delete":
          secrets.delete(args.providerId);
          return null;
        // plugin-store protocol
        case "plugin:store|load": {
          const rid = nextRid++;
          stores.set(rid, new Map());
          return rid;
        }
        case "plugin:store|get": {
          const m = stores.get(args.rid);
          if (!m) return null;
          return Object.prototype.hasOwnProperty.call(m, args.key) ? m[args.key] : null;
        }
        case "plugin:store|set":
          stores.get(args.rid)?.set(args.key, args.value);
          return null;
        case "plugin:store|has":
          return !!stores.get(args.rid)?.has(args.key);
        case "plugin:store|delete":
          stores.get(args.rid)?.delete(args.key);
          return null;
        case "plugin:store|save":
        case "plugin:store|reload":
        case "plugin:store|close":
        case "plugin:store|clear":
        case "plugin:store|reset":
          return null;
        case "plugin:store|keys":
          return Array.from(stores.get(args.rid)?.keys() ?? []);
        case "plugin:store|values":
          return Array.from(stores.get(args.rid)?.values() ?? []);
        case "plugin:store|entries":
          return Array.from(stores.get(args.rid)?.entries() ?? []);
        case "plugin:store|length":
          return stores.get(args.rid)?.size ?? 0;
        case "plugin:store|has_store":
          return true;
        // plugin-event protocol
        case "plugin:event|listen": {
          const id = nextHandlerId++;
          let bag = eventHandlers.get(args.event);
          if (!bag) {
            bag = new Map();
            eventHandlers.set(args.event, bag);
          }
          const cb = (window as any)["_" + args.handler];
          if (typeof cb === "function") bag.set(id, cb);
          return id;
        }
        case "plugin:event|unlisten":
          eventHandlers.get(args.event)?.delete(args.handler);
          return undefined;
        case "plugin:event|emit":
          fire(args.event, args.payload);
          return undefined;
        case "plugin:event|listen_once":
          return 0;
        default:
          throw new Error("mock-tauri: unhandled command \"" + cmd + "\"");
      }
    }
    (window as any).__MOCK_DISPATCH__ = dispatch;
  });

  // 4. Internals — installs `__TAURI_INTERNALS__` with invoke +
  //    transformCallback + event. The dispatcher and the rest are
  //    picked up from `window.__MOCK_DISPATCH__` etc.
  await page.addInitScript(function () {
    const dispatch = (window as any).__MOCK_DISPATCH__;
    if (!dispatch) return;
    (window as any).__TAURI_INTERNALS__ = {
      invoke: function (cmd: string, args: unknown) {
        return Promise.resolve().then(function () {
          return dispatch(cmd, args);
        });
      },
      transformCallback: function (callback: (e: any) => void) {
        const id = Math.floor(Math.random() * 1e9);
        (window as any)["_" + id] = callback;
        return id;
      },
      metadata: {
        currentWindowLabel: "main",
        currentWebview: { label: "main", windowLabel: "main" },
      },
    };
    (window as any).__TAURI_INTERNALS__.event = {
      listen: function () {
        return Promise.resolve(function () {});
      },
      emit: function () {
        return Promise.resolve();
      },
    };
  });
}

/** Read the invoke-call log from the page. Useful for assertions like
 *  "clicking Start should call `run_k6` exactly once". */
export async function readInvokeLog(page: Page): Promise<InvokeCall[]> {
  return page.evaluate(() => (window as any).__INVOKE_LOG__ ?? []);
}

/** Wait until the given invoke command appears in the log, returning
 *  the matching call. Times out via Playwright's default assertion
 *  timeout. */
export async function waitForInvoke(
  page: Page,
  cmd: string,
): Promise<InvokeCall> {
  const start = Date.now();
  while (Date.now() - start < 5_000) {
    const log = await readInvokeLog(page);
    const hit = log.find((c) => c.cmd === cmd);
    if (hit) return hit;
    await page.waitForTimeout(50);
  }
  throw new Error(`mock-tauri: timed out waiting for invoke("${cmd}")`);
}
