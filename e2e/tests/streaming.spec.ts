/**
 * Streaming e2e.
 *
 * Monaco's web workers don't boot reliably inside headless chromium,
 * so these tests verify the streaming pipeline by observing the mock
 * side rather than the editor DOM. The mock records every delta /
 * started / done frame it dispatches; the tests assert that the
 * events fire in the right shape and order — which is the contract
 * the Vue store's `useLlmStream` composable depends on.
 */
import { test, expect } from "../fixtures";
import { gotoApp, gotoAppWithMock, waitForAppReady } from "../helpers";

interface StreamFrame {
  phase: "started" | "delta" | "done" | "error";
  request_id?: string;
  text?: string;
  model?: string;
  tokens_in?: number;
  tokens_out?: number;
}

declare global {
  interface Window {
    __STREAM_FRAMES__?: StreamFrame[];
  }
}

const MOCK_SCRIPT = [
  "// generated by e2e streaming mock",
  'import http from "k6/http";',
  'import { check, sleep } from "k6";',
  "",
  "export const options = { vus: 5, duration: \"10s\" };",
  "",
  "export default function () {",
  "  const res = http.get(\"https://test.k6.io/\");",
  "  check(res, { \"status is 200\": r => r.status === 200 });",
  "  sleep(1);",
  "}",
  "",
].join("\n");

async function readChunkFrames(page: import("@playwright/test").Page): Promise<StreamFrame[]> {
  return page.evaluate(() => (window as any).__STREAM_FRAMES__ ?? []);
}

test.describe("LLM streaming end-to-end", () => {
  test.describe.configure({ mode: "serial" });
  test.setTimeout(60_000);

  async function goToAiWithChunkedStream(
    page: import("@playwright/test").Page,
    chunkSize: number,
    delayMs: number,
  ) {
    await gotoAppWithMock(page, "/ai", {
      streamScript: MOCK_SCRIPT,
      streamChunkSize: chunkSize,
      streamChunkDelayMs: delayMs,
    });
    await waitForAppReady(page);
    if (!page.url().endsWith("/ai")) {
      await page.getByRole("button", { name: /AI Generate/i }).click();
      await page.waitForURL(/\/ai$/);
    }
    const prompt = page.locator("textarea").first();
    await prompt.waitFor({ state: "visible", timeout: 15_000 });
    return prompt;
  }

  test("clicking Generate dispatches started → deltas → done in order", async ({ page }) => {
    const prompt = await goToAiWithChunkedStream(page, 32, 10);
    await prompt.fill("simple smoke test");
    await page.getByRole("button", { name: /Generate k6 script/i }).click();

    await expect
      .poll(
        async () => {
          const frames = await readChunkFrames(page);
          return frames.filter((f) => f.phase === "done").length;
        },
        { timeout: 10_000 },
      )
      .toBeGreaterThan(0);

    const frames = await readChunkFrames(page);
    const phases = frames.map((f) => f.phase);
    expect(phases[0]).toBe("started");
    expect(phases[phases.length - 1]).toBe("done");
    const deltas = frames.filter((f) => f.phase === "delta");
    expect(deltas.length).toBeGreaterThan(1);

    // The deltas, when concatenated, must reconstruct the body. This
    // is the contract `useLlmStream` relies on — if any chunk is
    // dropped or duplicated the accumulated text would diverge.
    const reconstructed = deltas.map((f) => f.text ?? "").join("");
    expect(reconstructed).toBe(MOCK_SCRIPT);
  });

  test("the mock's generate_script_stream invoke fires with the user's prompt", async ({ page }) => {
    const prompt = await goToAiWithChunkedStream(page, 64, 5);
    await prompt.fill("body round-trip");
    await page.getByRole("button", { name: /Generate k6 script/i }).click();

    await expect
      .poll(
        async () =>
          page.evaluate(() => {
            const log = (window as any).__INVOKE_LOG__ ?? [];
            const call = log.find((c: any) => c.cmd === "generate_script_stream");
            if (!call) return null;
            const args = call.args || {};
            return args.request?.prompt ?? null;
          }),
        { timeout: 10_000 },
      )
      .toBe("body round-trip");
  });

  test("chunks preserve byte order across multiple clicks", async ({ page }) => {
    const prompt = await goToAiWithChunkedStream(page, 16, 5);

    // First click — wait for done.
    await prompt.fill("first run");
    await page.getByRole("button", { name: /Generate k6 script/i }).click();
    await expect
      .poll(
        async () => {
          const frames = await readChunkFrames(page);
          return frames.filter((f) => f.phase === "done").length;
        },
        { timeout: 10_000 },
      )
      .toBeGreaterThanOrEqual(1);
    const allAfterFirst = await readChunkFrames(page);
    const firstBody = allAfterFirst
      .filter((f) => f.phase === "delta")
      .map((f) => f.text ?? "")
      .join("");
    expect(firstBody).toBe(MOCK_SCRIPT);

    // Second click — should produce another full sequence.
    await prompt.fill("second run");
    await page.getByRole("button", { name: /Generate k6 script/i }).click();
    await expect
      .poll(
        async () => {
          const frames = await readChunkFrames(page);
          return frames.filter((f) => f.phase === "done").length;
        },
        { timeout: 10_000 },
      )
      .toBeGreaterThanOrEqual(2);

    const all = await readChunkFrames(page);
    const secondDeltas = all
      .filter((f) => f.phase === "delta")
      .slice(firstBody.length / 16 + 1);
    expect(secondDeltas.length).toBeGreaterThan(0);
  });
});
